export function ShareButtons({ title, url }: { title: string; url: string }) {
  const [copied, setCopied] = useState(false);

  async function onCopy() {
    try {
      await navigator.clipboard.writeText(url);
      setCopied(true);
      setTimeout(() => setCopied(false), 1500);
    } catch {}
  }

  return (
    <div className="flex flex-wrap items-center gap-1">
      <span className="text-sm text-muted-foreground mr-2">Поделиться:</span>

      {networks.map((n) => (
        <a
          key={n.id}
          href={n.href(url, title)}
          target="_blank"
          rel="noopener noreferrer"
          title={n.label}
          className={`inline-flex h-9 w-9 items-center justify-center rounded-md border text-muted-foreground transition-colors hover:bg-muted ${n.color}`}
        >
          {n.icon}
        </a>
      ))}

      <button
        type="button"
        onClick={onCopy}
        title="Копировать ссылку"
        className="inline-flex h-9 w-9 items-center justify-center rounded-md border text-muted-foreground transition-colors hover:bg-muted hover:text-foreground"
      >
        {copied ? <Check className="h-4 w-4 text-green-500" /> : <Copy className="h-4 w-4" />}
      </button>
    </div>
  );
}
